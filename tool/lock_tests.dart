// Maintainer only: computes each problem's expected.json from the private reference solutions.
//
// Usage:
//   dart run tool/lock_tests.dart                     all problems that have a tests.dart
//   dart run tool/lock_tests.dart array               one category (same filters as start.dart)
//   dart run tool/lock_tests.dart --ref <dir> array   reference repo elsewhere (default: ../dsa_practice_reference)
//   dart run tool/lock_tests.dart --check array       only verify; don't write expected.json
//
// Reference repo layout mirrors this one: <problem path>/reference.dart (required, efficient) and
// optionally <problem path>/brute.dart (simple, slow). When brute.dart exists, both must give the same
// answers on every small case, which catches mistakes in either one.
// expected.json stores only fingerprints of the answers, never the answers themselves.
import 'dart:convert';
import 'dart:io';

import 'src/repo.dart';
import 'src/test_build.dart';

Future<void> main(List<String> args) async {
  final ri = args.indexOf('--ref');
  final refRoot = Directory(ri >= 0 ? args[ri + 1] : '${repoRoot.parent.path}/dsa_practice_reference').absolute;
  final checkOnly = args.contains('--check');
  final filters = [
    for (var i = 0; i < args.length; i++)
      if (!args[i].startsWith('--') && (i == 0 || args[i - 1] != '--ref')) args[i],
  ];
  if (!refRoot.existsSync()) {
    stderr.writeln('Reference repo not found at ${refRoot.path} (use --ref <dir>).');
    exit(1);
  }

  final all = loadProblems();
  final scope = filters.isEmpty
      ? all
      : filters.every((f) => f.contains('/'))
          ? [for (final f in filters) ...resolveProblems(all, [f])]
          : resolveProblems(all, filters);
  final problems = scope.where((p) => !p.isConcept && File('${repoRoot.path}/${p.path}/$testsFileName').existsSync()).toList();
  if (problems.isEmpty) {
    stdout.writeln('No problems with $testsFileName in that selection.');
    return;
  }

  final targets = <TestTarget>[];
  final missing = <Problem>[];
  for (final p in problems) {
    final ref = File('${refRoot.path}/${p.path}/reference.dart');
    if (!ref.existsSync()) {
      missing.add(p);
      continue;
    }
    targets.add(TestTarget(p, 'reference', ref));
  }
  final brutes = [
    for (final t in targets)
      if (File('${refRoot.path}/${t.problem.path}/brute.dart').existsSync())
        TestTarget(t.problem, 'brute', File('${refRoot.path}/${t.problem.path}/brute.dart')),
  ];

  // Package imports in reference files resolve through this repo's package config.
  _linkPackageConfig(refRoot);

  stdout.writeln('Running ${targets.length} reference and ${brutes.length} brute-force solution(s)…');
  final refResults = await runTests(targets, record: true, verbose: true, log: stdout.writeln);
  final bruteResults = await runTests(brutes, record: true, verbose: true, smallOnly: true,
      timeout: const Duration(seconds: 120), log: stdout.writeln);
  final bruteByProblem = {for (var i = 0; i < brutes.length; i++) brutes[i].problem.path: bruteResults[i]};

  var ok = 0;
  final problemsFound = <String>[];
  for (var i = 0; i < targets.length; i++) {
    final p = targets[i].problem;
    final r = refResults[i];
    if (r['status'] != 'pass') {
      problemsFound.add('${p.path}: reference ${r['status']}: ${r['message'] ?? r['failure'] ?? ''}'
          '${r['input'] == null ? '' : '\n    input: ${r['input']}'}');
      continue;
    }
    final hashes = (r['hashes'] as List).cast<String>();
    final b = bruteByProblem[p.path];
    if (b != null) {
      if (b['status'] != 'pass') {
        problemsFound.add('${p.path}: brute ${b['status']}: ${b['message'] ?? ''}');
        continue;
      }
      final bh = (b['hashes'] as List).cast<String>();
      final diff = [for (var k = 0; k < hashes.length; k++) if (bh[k].isNotEmpty && bh[k] != hashes[k]) k];
      if (diff.isNotEmpty) {
        problemsFound.add('${p.path}: reference and brute disagree on case(s) ${diff.take(10).join(', ')}');
        continue;
      }
    }
    if (!checkOnly) {
      final f = File('${repoRoot.path}/${p.path}/$expectedFileName');
      final json = const JsonEncoder.withIndent('  ').convert({
        'note': 'Fingerprints of the expected answers, generated by tool/lock_tests.dart. Do not edit.',
        'cases': hashes.length,
        'hashes': hashes,
      });
      f.writeAsStringSync('$json\n');
    }
    ok++;
    stdout.writeln('  ✅ ${p.path} (${hashes.length} cases, reference ${_ms(r['timeUs'])}'
        '${b == null ? '' : ', brute agrees'})');
  }

  stdout.writeln('\n$ok/${targets.length} locked${checkOnly ? ' (check only, nothing written)' : ''}.');
  for (final m in missing) {
    stdout.writeln('  ⚠️  no reference.dart for ${m.path}');
  }
  for (final e in problemsFound) {
    stdout.writeln('  ❌ $e');
  }
  if (problemsFound.isNotEmpty || missing.isNotEmpty) exit(1);
}

String _ms(Object? us) => us is int ? '${(us / 1000).toStringAsFixed(1)} ms' : '-';

void _linkPackageConfig(Directory refRoot) {
  final src = File('${repoRoot.path}/.dart_tool/package_config.json');
  if (!src.existsSync()) {
    Process.runSync('dart', ['pub', 'get'], workingDirectory: repoRoot.path);
  }
  final cfg = jsonDecode(src.readAsStringSync()) as Map<String, dynamic>;
  // Rewrite relative package roots to absolute ones so the copy works from the reference repo.
  for (final p in (cfg['packages'] as List).cast<Map<String, dynamic>>()) {
    final root = p['rootUri'] as String;
    if (!root.contains(':')) p['rootUri'] = Uri.directory('${repoRoot.path}/.dart_tool/').resolve(root).toString();
  }
  final dst = File('${refRoot.path}/.dart_tool/package_config.json');
  dst.parent.createSync(recursive: true);
  dst.writeAsStringSync(jsonEncode(cfg));
}
