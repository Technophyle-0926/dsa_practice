// Builds everyone's progress from the solution files.
//
// Usage:
//   dart run tool/progress.dart          regenerate PROGRESS.md, progress/<user>.md and README tables
//   dart run tool/progress.dart --me     print your own progress (does not write files)
//
// A problem counts as solved by <user> when <problem>/solutions/<user>.dart exists, no longer contains
// `UnimplementedError`, and passes the tests if the problem has them (results.json, written by GitHub).
// Reading notes (.md) count once the template's placeholder line is gone.
// On GitHub this runs automatically after every merge to main; you don't need to commit its output.

import 'dart:io';

import 'src/repo.dart';
import 'src/results.dart';

const _start = '<!-- progress:start -->';
const _end = '<!-- progress:end -->';
const _sigStart = '<!-- signature:start -->';
const _sigEnd = '<!-- signature:end -->';
const _resStart = '<!-- results:start -->';
const _resEnd = '<!-- results:end -->';

void main(List<String> args) {
  final problems = loadProblems();
  final standings = {for (final p in problems) p.path: ProblemStanding.of(p)};
  final solved = {for (final p in problems) p.path: standings[p.path]!.solvers};
  final users = {for (final st in standings.values) ...st.implemented}.toList();

  if (args.contains('--me')) {
    final me = readUser();
    if (me == null) {
      stderr.writeln('No username yet. Run: dart run tool/start.dart --user <github-username>');
      exit(1);
    }
    _printUser(me, problems, standings);
    return;
  }

  final categories = <String, List<Problem>>{};
  for (final p in problems) {
    categories.putIfAbsent(p.categoryDir, () => []).add(p);
  }
  int count(String user, Iterable<Problem> ps) => ps.where((p) => solved[p.path]!.contains(user)).length;

  // Ranking: most solved first, then name.
  users.sort((a, b) {
    final c = count(b, problems).compareTo(count(a, problems));
    return c != 0 ? c : a.toLowerCase().compareTo(b.toLowerCase());
  });

  _writeIfChanged('PROGRESS.md', _overall(users, problems, categories, count));
  _writeIfChanged('LEADERBOARD.md', _leaderboard(users, categories, standings));

  final progressDir = Directory('${repoRoot.path}/progress')..createSync(recursive: true);
  final expected = <String>{};
  for (final u in users) {
    expected.add('$u.md');
    _writeIfChanged('progress/$u.md', _userPage(u, categories, solved, count, standings));
  }
  // Remove pages of users who no longer have any solved problems.
  for (final f in progressDir.listSync().whereType<File>()) {
    final name = f.uri.pathSegments.last;
    if (name.endsWith('.md') && !expected.contains(name)) f.deleteSync();
  }

  // README tables (category + level).
  for (final entry in categories.entries) {
    final ps = entry.value;
    _replaceTable('${entry.key}/README.md', _table(ps, standings, withLevel: true));
    final levels = <String, List<Problem>>{};
    for (final p in ps) {
      levels.putIfAbsent(p.levelDir, () => []).add(p);
    }
    for (final l in levels.entries) {
      _replaceTable('${entry.key}/${l.key}/README.md', _table(l.value, standings, withLevel: false));
    }
  }
  // Signature section of every problem README, rendered from problem.json.
  for (final p in problems.where((p) => !p.isConcept)) {
    _replaceBetween('${p.path}/README.md', _sigStart, _sigEnd, _signatureSection(p));
    final st = standings[p.path]!;
    if (st.tested) {
      _ensureMarkers('${p.path}/README.md');
      _replaceBetween('${p.path}/README.md', _resStart, _resEnd, _resultsSection(st));
    }
  }
  stdout.writeln('Progress updated for ${users.length} contributor(s), ${problems.length} problems.');
}

String _overall(List<String> users, List<Problem> problems, Map<String, List<Problem>> categories,
    int Function(String, Iterable<Problem>) count) {
  final b = StringBuffer()
    ..writeln('# Progress')
    ..writeln()
    ..writeln('_Generated by `tool/progress.dart` after every merge to `main`. Do not edit by hand._')
    ..writeln()
    ..writeln('Speed ranking: [LEADERBOARD.md](LEADERBOARD.md).')
    ..writeln();
  if (users.isEmpty) {
    b.writeln('No solutions yet. Start one with `dart run tool/start.dart <problem folder>`.');
    return b.toString();
  }
  b
    ..writeln('## Ranking')
    ..writeln()
    ..writeln('| Rank | Contributor | Solved | % of ${problems.length} |')
    ..writeln('|---|---|---|---|');
  for (var i = 0; i < users.length; i++) {
    final c = count(users[i], problems);
    b.writeln('| ${i + 1} | [${users[i]}](progress/${users[i]}.md) | $c | ${(100 * c / problems.length).toStringAsFixed(1)}% |');
  }
  b
    ..writeln()
    ..writeln('## By category')
    ..writeln()
    ..writeln('| Category | Total | ${users.join(' | ')} |')
    ..writeln('|---|---|${'---|' * users.length}');
  for (final e in categories.entries) {
    final name = e.value.first.category;
    b.writeln('| [$name](${e.key}/README.md) | ${e.value.length} | '
        '${users.map((u) => count(u, e.value)).join(' | ')} |');
  }
  return b.toString();
}

String _userPage(String user, Map<String, List<Problem>> categories, Map<String, List<String>> solved,
    int Function(String, Iterable<Problem>) count, Map<String, ProblemStanding> standings) {
  final all = categories.values.expand((e) => e).toList();
  final points = standings.values.fold<double>(0, (a, st) => a + (st.points[user] ?? 0));
  final failing = all.where((p) => standings[p.path]!.failingFor(user)).toList();
  final b = StringBuffer()
    ..writeln('# $user')
    ..writeln()
    ..writeln('_Generated by `tool/progress.dart`. Do not edit by hand._')
    ..writeln()
    ..writeln('**Solved:** ${count(user, all)} / ${all.length} · **Points:** ${points.toStringAsFixed(1)} '
        '([leaderboard](../LEADERBOARD.md))')
    ..writeln();
  if (failing.isNotEmpty) {
    b
      ..writeln('## Not passing yet')
      ..writeln()
      ..writeln('| Problem | Result |')
      ..writeln('|---|---|');
    for (final p in failing) {
      b.writeln('| [${p.category} ${p.level} ${p.number}. ${p.title.replaceAll('|', '\\|')}](../${p.path}/README.md) | '
          '❌ ${statusLabel(standings[p.path]!.results[user])} |');
    }
    b.writeln();
  }
  b
    ..writeln('| Category | Level | Solved |')
    ..writeln('|---|---|---|');
  for (final e in categories.entries) {
    final levels = <String, List<Problem>>{};
    for (final p in e.value) {
      levels.putIfAbsent(p.level, () => []).add(p);
    }
    for (final l in levels.entries) {
      final c = count(user, l.value);
      b.writeln('| ${e.value.first.category} | ${l.key} | $c / ${l.value.length}${c == l.value.length ? ' ✅' : ''} |');
    }
  }
  b
    ..writeln()
    ..writeln('## Solved problems')
    ..writeln();
  for (final e in categories.entries) {
    final done = e.value.where((p) => solved[p.path]!.contains(user)).toList();
    if (done.isEmpty) continue;
    b
      ..writeln('### ${e.value.first.category}')
      ..writeln();
    for (final p in done) {
      final st = standings[p.path]!;
      final extra = st.tested
          ? ' · ${formatMs(st.results[user]?['timeUs'])} · ${st.points[user]!.toStringAsFixed(1)} pts'
          : '';
      b.writeln('- [${p.level} ${p.number}. ${p.title}](../${p.path}/solutions/${p.solutionFile(user).uri.pathSegments.last})$extra');
    }
    b.writeln();
  }
  return b.toString();
}

String _table(List<Problem> ps, Map<String, ProblemStanding> standings, {required bool withLevel}) {
  final b = StringBuffer()
    ..writeln(withLevel ? '| Level | # | Problem | GfG | Solved by |' : '| # | Problem | GfG | Solved by |')
    ..writeln(withLevel ? '|---|---|---|---|---|' : '|---|---|---|---|');
  for (final p in ps) {
    final rel = withLevel ? '${p.levelDir}/${p.problemDir}' : p.problemDir;
    final st = standings[p.path]!;
    String link(String u) => '[$u]($rel/solutions/${p.solutionFile(u).uri.pathSegments.last})';
    final String by;
    if (st.tested) {
      final passing = st.solvers..sort((a, b) => (st.points[b] ?? 0).compareTo(st.points[a] ?? 0));
      final failing = st.implemented.where(st.failingFor);
      by = [
        for (final u in passing) '${link(u)} ${formatMs(st.results[u]?['timeUs'])}',
        for (final u in failing) '${link(u)} ❌',
      ].join(', ');
    } else {
      by = st.solvers.map(link).join(', ');
    }
    final title = p.title.replaceAll('|', '\\|');
    b.writeln('${withLevel ? '| ${p.level} ' : ''}| ${p.number} | [$title]($rel/README.md) | [link](${p.link}) | $by |');
  }
  return b.toString().trimRight();
}

void _replaceTable(String rel, String table) => _replaceBetween(rel, _start, _end, table);

void _replaceBetween(String rel, String startMarker, String endMarker, String content) {
  final f = File('${repoRoot.path}/$rel');
  if (!f.existsSync()) return;
  final text = f.readAsStringSync();
  final s = text.indexOf(startMarker);
  final e = text.indexOf(endMarker);
  if (s < 0 || e < s) return;
  final updated = '${text.substring(0, s + startMarker.length)}\n$content\n${text.substring(e)}';
  if (updated != text) f.writeAsStringSync(updated);
}

String _signatureSection(Problem p) {
  final fn = p.meta['function'] as Map<String, dynamic>;
  final verified = fn['verified'] == true;
  final params = (fn['params'] as List).cast<Map<String, dynamic>>();
  final b = StringBuffer()
    ..writeln('## Function Signature')
    ..writeln()
    ..writeln('```dart')
    ..writeln(verified
        ? '${fn['returns']} ${fn['name']}(${params.map((e) => '${e['type']} ${e['name']}').join(', ')})'
        : 'dynamic ${fn['name']}(/* not set yet */)')
    ..writeln('```')
    ..writeln();
  final note = fn['note'] as String?;
  if (note != null && note.isNotEmpty) {
    b
      ..writeln('> **Note:** $note')
      ..writeln();
  }
  b.writeln(verified
      ? 'Your solution must define this function with the same name and parameters; the leaderboard calls it.'
      : '_The signature for this problem has not been set yet. Pick parameters that fit the problem; '
          'it will be fixed in `problem.json` before it joins the leaderboard._');
  final example = p.meta['example'] as Map<String, dynamic>?;
  if (verified && example != null) {
    final exp = (example['expected'] as String).trim();
    b
      ..writeln()
      ..writeln('**Example:** `${example['call']}`${exp.isEmpty ? '' : ' → `$exp`'}');
  }
  return b.toString().trimRight();
}

void _writeIfChanged(String rel, String content) {
  final f = File('${repoRoot.path}/$rel');
  if (f.existsSync() && f.readAsStringSync() == content) return;
  f.writeAsStringSync(content);
}

void _printUser(String me, List<Problem> problems, Map<String, ProblemStanding> standings) {
  final mine = problems.where((p) => standings[p.path]!.solvedBy(me)).toList();
  final points = standings.values.fold<double>(0, (a, st) => a + (st.points[me] ?? 0));
  stdout.writeln('$me: ${mine.length} / ${problems.length} solved, ${points.toStringAsFixed(1)} points\n');
  final byCat = <String, List<Problem>>{};
  for (final p in problems) {
    byCat.putIfAbsent(p.category, () => []).add(p);
  }
  for (final e in byCat.entries) {
    final c = e.value.where(mine.contains).length;
    if (c > 0) stdout.writeln('  ${e.key.padRight(24)} $c / ${e.value.length}');
  }
  final failing = problems.where((p) => standings[p.path]!.failingFor(me)).toList();
  if (failing.isNotEmpty) {
    stdout.writeln('\nNot passing the tests (as of your last pull):');
    for (final p in failing) {
      stdout.writeln('  ${shortcut(p).padRight(28)} ${statusLabel(standings[p.path]!.results[me])}');
    }
    stdout.writeln('  Check one with: dart run tool/test.dart <problem>');
  }
  final started = problems.where((p) => p.solutionFile(me).existsSync() && !standings[p.path]!.implemented.contains(me));
  if (started.isNotEmpty) {
    stdout.writeln('\nStarted but not finished (placeholder still there):');
    for (final p in started) {
      stdout.writeln('  ${p.path}');
    }
  }
}

String _leaderboard(List<String> users, Map<String, List<Problem>> categories, Map<String, ProblemStanding> standings) {
  double pts(String u, Iterable<Problem> ps) => ps.fold<double>(0, (a, p) => a + (standings[p.path]!.points[u] ?? 0));
  int passed(String u) => standings.values.where((st) => st.tested && st.solvedBy(u)).length;
  int failing(String u) => standings.values.where((st) => st.failingFor(u)).length;
  final all = categories.values.expand((e) => e).toList();
  final tested = standings.values.where((st) => st.tested).length;
  final ranked = [...users]..sort((a, b) {
      final c = pts(b, all).compareTo(pts(a, all));
      return c != 0 ? c : a.toLowerCase().compareTo(b.toLowerCase());
    });
  final b = StringBuffer()
    ..writeln('# Leaderboard')
    ..writeln()
    ..writeln('_Generated by `tool/progress.dart` after every merge to `main`. Do not edit by hand._')
    ..writeln()
    ..writeln('For every problem with tests that you pass, you get **100 × fastest time / your time** points:')
    ..writeln('the fastest solution gets 100, one taking twice as long gets 50. Failing solutions get 0.')
    ..writeln('Times under 1 ms count as 1 ms (smaller differences are just measurement noise).')
    ..writeln('Times are measured on GitHub; all solutions to a problem are re-run together whenever someone')
    ..writeln('submits it, so they are compared on the same machine. '
        '$tested problem${tested == 1 ? ' has' : 's have'} tests so far.')
    ..writeln();
  if (ranked.isEmpty) {
    b.writeln('No solutions yet.');
    return b.toString();
  }
  b
    ..writeln('| Rank | Contributor | Points | Passing tests | Not passing |')
    ..writeln('|---|---|---|---|---|');
  for (var i = 0; i < ranked.length; i++) {
    final u = ranked[i];
    b.writeln('| ${i + 1} | [$u](progress/$u.md) | ${pts(u, all).toStringAsFixed(1)} | ${passed(u)} | ${failing(u)} |');
  }
  final testedCats = categories.entries.where((e) => e.value.any((p) => standings[p.path]!.tested)).toList();
  if (testedCats.isNotEmpty) {
    b
      ..writeln()
      ..writeln('## Points by category')
      ..writeln()
      ..writeln('| Category | Tested problems | ${ranked.join(' | ')} |')
      ..writeln('|---|---|${'---|' * ranked.length}');
    for (final e in testedCats) {
      final n = e.value.where((p) => standings[p.path]!.tested).length;
      b.writeln('| [${e.value.first.category}](${e.key}/README.md) | $n | '
          '${ranked.map((u) => pts(u, e.value).toStringAsFixed(1)).join(' | ')} |');
    }
  }
  return b.toString();
}

String _resultsSection(ProblemStanding st) {
  final b = StringBuffer()
    ..writeln('## Leaderboard')
    ..writeln()
    ..writeln('Test it on your computer first: `dart run tool/test.dart ${shortcut(st.problem)}`')
    ..writeln();
  final users = [...st.implemented]..sort((a, c) {
      final pa = st.points[a] ?? -1, pc = st.points[c] ?? -1;
      return pa != pc ? pc.compareTo(pa) : a.toLowerCase().compareTo(c.toLowerCase());
    });
  if (users.isEmpty) {
    b.writeln('_No solutions yet._');
    return b.toString().trimRight();
  }
  b
    ..writeln('| # | Contributor | Result | Time | Extra memory | Points |')
    ..writeln('|---|---|---|---|---|---|');
  var rank = 0;
  for (final u in users) {
    final r = st.results[u];
    final pass = r?['status'] == 'pass';
    if (pass) rank++;
    b.writeln('| ${pass ? rank : '–'} | $u | ${pass ? '✅ ${r!['passed']}/${r['total']}' : '❌ ${statusLabel(r)}'} | '
        '${pass ? formatMs(r!['timeUs']) : '–'} | ${pass ? '${r!['memoryMb']} MB' : '–'} | '
        '${(st.points[u] ?? 0).toStringAsFixed(1)} |');
  }
  return b.toString().trimRight();
}

void _ensureMarkers(String rel) {
  final f = File('${repoRoot.path}/$rel');
  if (!f.existsSync()) return;
  final text = f.readAsStringSync();
  if (text.contains(_resStart)) return;
  f.writeAsStringSync('${text.trimRight()}\n\n$_resStart\n$_resEnd\n');
}
